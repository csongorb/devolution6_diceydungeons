/*Hover Popup Logic*/
function addHoverLinkPopup(rectangle, popupUrl) {
    var popupHovered = false;
    var closeTimer = null;

    function openPopup() {
        if (closeTimer !== null) {
            clearTimeout(closeTimer);
            closeTimer = null;
        }

        rectangle.openPopup();
    }

    function scheduleClose() {
        if (closeTimer !== null) {
            clearTimeout(closeTimer);
        }

        closeTimer = setTimeout(function() {
            if (!popupHovered) {
                rectangle.closePopup();
            }
        }, 100);
    }

    rectangle
        .bindPopup(`<center><a href="${popupUrl}" target="_blank">${popupUrl}</a></center>`, { closeButton: false })
        .on('mouseover', function(){
            openPopup();
        })
        .on('mouseout', function(){
            scheduleClose();
        })
        .on('popupopen', function() {
            var popupElement = rectangle.getPopup().getElement();

            if (!popupElement || popupElement._hoverEventsAdded) {
                return;
            }

            popupElement._hoverEventsAdded = true;
            popupElement.addEventListener('mouseenter', function() {
                popupHovered = true;
                if (closeTimer !== null) {
                    clearTimeout(closeTimer);
                    closeTimer = null;
                }
            });
            popupElement.addEventListener('mouseleave', function() {
                popupHovered = false;
                scheduleClose();
            });
        });

    return rectangle;
}